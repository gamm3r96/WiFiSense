import type { SensorSim, SimConfig, SourceMode, TelemetryPoint } from "../types";

export interface ExportMeta {
  platform: "WiFiSense Lab";
  format: 1;
  source: SourceMode;
  provenance: string;
  sensorId: string;
  sensorName: string;
  room: string;
  seed: number;
  sampleRateHz: number;
  subcarriers: number;
  frames: number;
  exportedAtISO: string;
}

export function buildMeta(s: SensorSim, cfg: SimConfig, mode: SourceMode): ExportMeta {
  return {
    platform: "WiFiSense Lab",
    format: 1,
    source: mode,
    provenance:
      mode === "simulation"
        ? "SYNTHETIC CSI generated by the deterministic simulation engine — not hardware measurements"
        : "Live hardware stream",
    sensorId: s.id,
    sensorName: s.name,
    room: s.roomName,
    seed: cfg.seed,
    sampleRateHz: cfg.sampleRate,
    subcarriers: cfg.subcarriers,
    frames: s.buffer.length,
    exportedAtISO: new Date().toISOString(),
  };
}

const CSV_HEADER = "t_s,amplitude,phase_rad,rssi_dbm,variance,motion_score";

export function toCSV(buffer: TelemetryPoint[]): string {
  const lines = [CSV_HEADER];
  for (const p of buffer) {
    lines.push(
      [
        p.t.toFixed(3),
        p.amp.toFixed(6),
        p.phase.toFixed(6),
        p.rssi.toFixed(2),
        p.variance.toExponential(4),
        p.score.toFixed(4),
      ].join(","),
    );
  }
  return lines.join("\n");
}

export function toJSON(meta: ExportMeta, buffer: TelemetryPoint[]): string {
  return JSON.stringify(
    {
      meta,
      columns: ["t_s", "amplitude", "phase_rad", "rssi_dbm", "variance", "motion_score"],
      rows: buffer.map((p) => [
        +p.t.toFixed(3),
        +p.amp.toFixed(6),
        +p.phase.toFixed(6),
        +p.rssi.toFixed(2),
        +p.variance.toExponential(4),
        +p.score.toFixed(4),
      ]),
    },
    null,
    2,
  );
}

/** RFC-4180-ish escape for label fields used by later dataset exports. */
export function csvEscape(v: string): string {
  return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
}

export function sanitizeFilename(name: string): string {
  return name.replace(/[^a-z0-9._-]+/gi, "_").replace(/_{2,}/g, "_").slice(0, 64) || "export";
}

export function downloadText(filename: string, content: string, mime: string): void {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = sanitizeFilename(filename);
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}
